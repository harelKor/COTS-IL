/**
 * Writes .env.local from the running local Supabase stack (`npx supabase start`).
 * Keeps an existing SEED_PASSWORD so seeded logins keep working.
 */
import { execSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const status = JSON.parse(execSync("npx supabase status -o json", { encoding: "utf8" }));

const previous = existsSync(".env.local") ? readFileSync(".env.local", "utf8") : "";
const seedPassword =
  previous.match(/^SEED_PASSWORD=(.+)$/m)?.[1] ?? randomBytes(12).toString("base64url");

const env = {
  NEXT_PUBLIC_SITE_URL: "http://localhost:3000",
  NEXT_PUBLIC_SUPABASE_URL: status.API_URL,
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: status.PUBLISHABLE_KEY,
  SUPABASE_SECRET_KEY: status.SECRET_KEY,
  DATABASE_URL: status.DB_URL,
  SEED_PASSWORD: seedPassword,
};

writeFileSync(
  ".env.local",
  `# Generated by \`npm run env:local\` from the local Supabase stack. Do not commit.\n${Object.entries(env)
    .map(([k, v]) => `${k}=${v}`)
    .join("\n")}\n`,
);
console.log("Wrote .env.local");
